#!/usr/bin/env python3
"""NVD's yearly feeds, for labels at a scale the per-CVE API cannot reach.

`fetch_labels.py` asks the 2.0 API for one CVE at a time. That is right when the corpus is the
1,165 CVEs our own scans cite; it is hopeless for the 80,555 checks in the OpenVAS feed, which
between them reference tens of thousands more. At the API's polite rate of 0.7 s per request
that is most of a day. A yearly feed is 25 MB and arrives in about eighty seconds, and 2024
alone carries 39,254 CVEs of which 98% have a published CVSS vector.

WHAT IT KEEPS, AND WHY THIS FILE IS SEPARATE FROM cwe_map.json

The same four things `fetch_labels.py` records -- CWE, description, publication date, CVSS
vector -- plus the affected products, in the same shape, so downstream code can read either.
They stay in separate files because they answer different questions. `cwe_map.json` is the
corpus: every CVE our scans actually cited, and losing it would mean re-deriving every result
in `scans.md`. This is a training set: large, replaceable, and regenerated by re-running the
download.

The 1.1 feeds are gone -- they answer 403 now -- so the 2.0 layout is the only one available.
Version 4.0 vectors are read where present and 3.1 preferred over 3.0 over 2.0, matching the
preference already used for the corpus, so the two files never disagree about a CVE they
share.

A NOTE ON THE LABEL SPACE

CVSS v2 uses PARTIAL and COMPLETE where v3 uses LOW and HIGH, and mixing them puts two
vocabularies in one target. Measured on the corpus, that produced a `PARTIAL` class with three
examples and an F1 of zero, dragging down a macro average. Rows whose only vector is v2 are
therefore recorded with `cvss_version` set, so a caller can exclude them rather than discover
the problem in a confusion matrix.

    python3 fetch_nvd_bulk.py --from 2016 --to 2026
"""

import argparse
import datetime
import gzip
import io
import json
import os
import sys
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
FEED = "https://nvd.nist.gov/feeds/json/cve/2.0/nvdcve-2.0-{year}.json.gz"
OUT = os.path.join(HERE, "nvd_bulk.json")


def cvss_of(cve):
    """The newest vector present, with the version recorded so v2 rows can be excluded."""
    metrics = cve.get("metrics") or {}
    # 3.1 first, not 4.0. Two reasons: it is by far the largest group in these feeds, and it
    # is the vocabulary the corpus cache already speaks, so the two label sources cannot
    # disagree about a CVE they share. 4.0 is read where it is the only vector present, and
    # its impact fields are named differently -- a first version of this function preferred
    # 4.0 and then looked for 3.x field names, which silently stripped the impact metrics
    # from 38,732 CVEs and only showed up as a "no impact metrics" count downstream.
    for key, ver in (("cvssMetricV31", "3.1"), ("cvssMetricV30", "3.0"),
                     ("cvssMetricV40", "4.0"), ("cvssMetricV2", "2.0")):
        entries = metrics.get(key) or []
        if not entries:
            continue
        d = entries[0].get("cvssData", {})
        if ver == "4.0":
            impact = (d.get("vulnConfidentialityImpact", ""),
                      d.get("vulnIntegrityImpact", ""),
                      d.get("vulnAvailabilityImpact", ""))
        else:
            impact = (d.get("confidentialityImpact", ""),
                      d.get("integrityImpact", ""),
                      d.get("availabilityImpact", ""))
        return {
            "version": ver,
            "vector": d.get("vectorString", ""),
            "attackVector": d.get("attackVector") or d.get("accessVector", ""),
            "confidentiality": impact[0],
            "integrity": impact[1],
            "availability": impact[2],
            "baseScore": d.get("baseScore", ""),
        }
    return {}


def cpes_of(cve):
    found = set()
    for node in cve.get("configurations", []):
        for match in node.get("nodes", []):
            for m in match.get("cpeMatch", []):
                parts = (m.get("criteria") or "").split(":")
                if len(parts) > 5 and parts[2] and parts[3] and parts[4]:
                    found.add(f"{parts[2]}:{parts[3]}:{parts[4]}")
    return sorted(found)


def fetch_year(year):
    url = FEED.format(year=year)
    req = urllib.request.Request(url, headers={"User-Agent": "ThreatRank/1.0"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        blob = resp.read()
    return json.load(gzip.GzipFile(fileobj=io.BytesIO(blob)))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    this_year = datetime.date.today().year
    ap.add_argument("--from", dest="start", type=int, default=2016, metavar="YEAR")
    ap.add_argument("--to", dest="end", type=int, default=this_year, metavar="YEAR")
    ap.add_argument("-o", "--out", default=OUT, metavar="JSON")
    args = ap.parse_args()

    have = {}
    if os.path.exists(args.out):
        have = json.load(open(args.out, encoding="utf-8")).get("cves", {})
        print(f"resuming, {len(have)} CVEs already cached")

    years = list(range(args.start, args.end + 1))
    print(f"years             : {years[0]}-{years[-1]}, {len(years)} feeds\n")
    for year in years:
        try:
            data = fetch_year(year)
        except urllib.error.HTTPError as e:
            print(f"  {year}: HTTP {e.code}, skipped")
            continue
        except Exception as e:
            print(f"  {year}: {e}, skipped")
            continue
        added = 0
        for item in data.get("vulnerabilities", []):
            cve = item.get("cve") or {}
            cid = cve.get("id")
            if not cid:
                continue
            vector = cvss_of(cve)
            if not vector:
                continue
            cwes = sorted({d["value"] for w in cve.get("weaknesses", [])
                           for d in w.get("description", [])
                           if d["value"].startswith("CWE-")})
            desc = next((d["value"] for d in cve.get("descriptions", [])
                         if d["lang"] == "en"), "")
            have[cid] = {"cwes": cwes, "description": desc,
                         "published": cve.get("published", ""),
                         "cvss": vector, "cvss_version": vector["version"],
                         "cpes": cpes_of(cve)}
            added += 1
        print(f"  {year}: {len(data.get('vulnerabilities', [])):6d} CVEs, "
              f"{added:6d} with a vector")
        json.dump({"_source": "NVD 2.0 yearly feeds",
                   "_fetched": datetime.datetime.now().isoformat(timespec="seconds"),
                   "cves": have},
                  open(args.out, "w", encoding="utf-8"))

    versions = {}
    for v in have.values():
        versions[v["cvss_version"]] = versions.get(v["cvss_version"], 0) + 1
    print(f"\ntotal             : {len(have)} CVEs with a published vector")
    for k in sorted(versions, reverse=True):
        print(f"  CVSS {k:4s}       {versions[k]:7d}")
    v2 = versions.get("2.0", 0)
    if v2:
        print(f"\n  {v2} carry only a v2 vector, whose PARTIAL/COMPLETE vocabulary does not")
        print("  belong in a v3 label space. Exclude them on `cvss_version` rather than")
        print("  letting a three-example class appear in a confusion matrix.")
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
