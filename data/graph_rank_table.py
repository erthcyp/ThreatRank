"""Compare ThreatRank's use of the attack graph against ranking by the graph's structure.

Published attack-graph prioritization methods rank nodes by their position in the graph: their
centrality, the paths through them, their structural role (TriAssetRank, DefenceRank). ThreatRank
uses the graph differently -- as a reachability gate that zeroes a finding off every path to the
goal, with exploit likelihood doing the ranking within what remains. This script grades the two
uses of the same MulVAL graph on the one external label, CISA KEV, at each budget.

Three orderings are reported. ThreatRank is $L$ over the reachability gate. The structural ranking
is PageRank over the derivation graph, run backward from the goal so importance flows to the facts
the goal depends on -- the family the two cited papers belong to, read with no exploit signal.
The exploit-aware variant multiplies that centrality by $L$, to show that it collapses onto
ThreatRank: the derivation is so redundant (one goal rests on 168 findings) that centrality cannot
separate the findings, so the graph's whole contribution to the ranking is the gate.

    python3 graph_rank_table.py --graph ../mulval/cases/lab3/out \
        --topology topology_lab3.json --findings processed/findings_openvas_b2.csv \
        -o figures/tab_graphrank.tex
"""
import argparse
import collections
import json

import prioritise as P
import consequence as C

BUDGETS = [3, 5, 10, 25]


def pagerank(nodes, edges, damping=0.85, iterations=100):
    """PageRank over the reversed derivation graph, so rank flows from the goal to its premises."""
    succ = collections.defaultdict(list)
    for src, dsts in edges.items():
        for dst in dsts:
            succ[dst].append(src)          # reversed: dst -> src
    n = len(nodes)
    rank = {v: 1.0 / n for v in nodes}
    for _ in range(iterations):
        nxt = {v: (1 - damping) / n for v in nodes}
        for node in nodes:
            out = succ.get(node, [])
            if out:
                share = damping * rank[node] / len(out)
                for s in out:
                    nxt[s] += share
            else:
                share = damping * rank[node] / n
                for v in nodes:
                    nxt[v] += share
        rank = nxt
    return rank


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--graph", required=True, metavar="DIR")
    ap.add_argument("--topology", required=True, metavar="JSON")
    ap.add_argument("--findings", required=True, action="append", metavar="CSV")
    ap.add_argument("--weights", default="1,2,5")
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args()

    kept, actions, _topo = P.score(args.graph, args.topology, args.findings)
    weights = [float(x) for x in args.weights.split(",")]
    cost = dict(zip((P.PATCH, P.CONFIG, P.REPLACE), weights))

    verts, edges = C.read_graph(args.graph)
    leaves = C.finding_leaves(verts)
    goals = C.goal_vertex(verts, json.load(open(args.topology, encoding="utf-8"))["goal"])
    dist = C.distances_to(goals, edges, verts)
    rank = pagerank(set(verts), edges)
    top = max(rank.values()) or 1.0
    for r in kept:
        vid = leaves.get((r["atom"], r["vuln_id"]))
        reach = vid is not None and dist.get(vid) is not None
        r["_cpr"] = (rank[vid] / top) if reach else 0.0

    total_cost = sum(cost[a["tier"]] for a in actions)
    kev_total = sum(1 for r in kept if P.in_kev(r))

    def greedy(value, budget):
        chosen, spent = [], 0.0
        for a in sorted(actions, key=lambda a: -(value(a) / cost[a["tier"]])):
            c = cost[a["tier"]]
            if spent + c <= budget:
                chosen.append(a)
                spent += c
        return chosen

    def kev_at(value):
        return [sum(a["kev"] for a in greedy(value, total_cost * b / 100.0)) for b in BUDGETS]

    rows = [
        ("ThreatRank, $R = L \\times C$", kev_at(lambda a: a["risk"])),
        ("Graph-structural rank~\\cite{triassetrank,defencerank}",
         kev_at(lambda a: sum(r["_cpr"] for r in a["members"]))),
        ("\\quad the same, weighted by likelihood",
         kev_at(lambda a: sum(r["likelihood"] * r["_cpr"] for r in a["members"]))),
    ]

    lines = [
        "% generated by graph_rank_table.py; do not edit by hand",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        f"Ordering & \\multicolumn{{4}}{{c}}{{KEV closed (of {kev_total})}} \\\\",
        "& 3\\% & 5\\% & 10\\% & 25\\% \\\\",
        "\\midrule",
    ]
    for label, kev in rows:
        lines.append(f"{label} & " + " & ".join(str(v) for v in kev) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    for label, kev in rows:
        print(f"  {label[:40]:40s} {kev}")


if __name__ == "__main__":
    main()
