#!/usr/bin/env python3
"""Emit the cross-scanner robustness table by running risk.py once per scanner.

Experiment 3 grades R = L x C against the severity list on the graph corpus, from OpenVAS
alone, because the recorded graph rests on that scanner's facts. This reruns the identical
grading with Nessus and with Qualys mapped onto the same graph, so the table shows whether the
method's advantage over severity depends on the scanner. Numbers are read from risk.py's own
output, never retyped.

    python3 robustness_table.py \
        --graph ~/mulval/testcases/lab3 --topology topology_lab3.json \
        -o figures/tab_robustness.tex
"""

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# (label, findings CSV), in the order a defender would reach for them.
SCANNERS = [
    ("OpenVAS", "processed/findings_openvas_b2.csv"),
    ("Nessus", "processed/findings_nessus_b2.csv"),
    ("Qualys", "processed/findings_qualys_b2.csv"),
]


def run_risk(graph, topology, findings):
    out = subprocess.run(
        [sys.executable, os.path.join(HERE, "risk.py"),
         "--graph", graph, "--topology", topology, "--findings", findings],
        cwd=HERE, capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"risk.py failed on {findings}:\n{out.stderr}")
    return out.stdout


def parse(text):
    """Pull the scoped (CVE-only) grading: #findings, #KEV, and P@5 / first-KEV per ordering."""
    kev = int(re.search(r"known exploited\s*:\s*(\d+)", text).group(1))
    n_cve = int(re.search(r"SCOPED TO THE (\d+) FINDINGS", text).group(1))
    # the scoped block, up to the whole-list block
    scoped = text.split("SCOPED TO THE", 1)[1].split("THE WHOLE LIST", 1)[0]
    rows = {}
    for name in ("R = L x C", "severity"):
        m = re.search(re.escape(name) + r"\s+([\d.]+)(?:\s+[\d.]+)*\s+(\d+)\s*$",
                      scoped, re.M)
        if m:
            rows[name] = (float(m.group(1)), int(m.group(2)))   # (P@5, first-KEV)
    return n_cve, kev, rows


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--graph", required=True)
    ap.add_argument("--topology", required=True)
    ap.add_argument("-o", "--out", default="figures/tab_robustness.tex")
    args = ap.parse_args()
    graph = os.path.expanduser(args.graph)

    lines = ["% generated by robustness_table.py -- do not edit by hand",
             "\\begin{tabular}{lrr rr rr}",
             "\\toprule",
             " & & & \\multicolumn{2}{c}{P@5} & \\multicolumn{2}{c}{First KEV rank} \\\\",
             "\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
             "Scanner & CVE find. & KEV & $R{=}L{\\times}C$ & severity "
             "& $R{=}L{\\times}C$ & severity \\\\",
             "\\midrule"]
    for label, csv in SCANNERS:
        text = run_risk(graph, args.topology, csv)
        n_cve, kev, rows = parse(text)
        r = rows.get("R = L x C")
        s = rows.get("severity")
        if not r or not s:
            lines.append(f"{label} & {n_cve} & {kev} & \\multicolumn{{4}}{{c}}"
                         f"{{too few findings to grade}} \\\\")
            continue
        # bold the method's cell when it strictly beats severity on that metric
        p5r = f"\\textbf{{{r[0]:.2f}}}" if r[0] > s[0] else f"{r[0]:.2f}"
        kvr = f"\\textbf{{{r[1]}}}" if r[1] < s[1] else f"{r[1]}"
        lines.append(f"{label} & {n_cve} & {kev} & {p5r} & {s[0]:.2f} "
                     f"& {kvr} & {s[1]} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]

    path = os.path.join(HERE, args.out)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\n  wrote {path}")


if __name__ == "__main__":
    main()
