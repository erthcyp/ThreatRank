"""Generate tab:corpus from the current parsed findings, so the table in the paper is a product
of the data rather than a transcription of it.

Counts are per scanner and exclude log-level / informational findings, exactly as the OpenVAS and
Nessus columns always did: a row counts when its ``threat`` is not ``Log``. Qualys' INFO and
SERVICE types are marked ``Log`` by parse_qualys.py for this reason, so the three scanners are
filtered identically. ``KEV`` is the count of known-exploited *findings* (rows), summed over the
three scanners, on the same per-scanner basis as the finding columns; a vulnerability found by two
scanners is two findings and is counted twice, just as it is in those columns. ``Per host`` is all
reported findings over the hosts in the group.

Hosts are assigned to groups by address, which is the single authoritative map; a scanner's own
``group`` column is not trusted here so that the three scanners cannot disagree about membership.

    python3 corpus_table.py -o figures/tab_corpus.tex
"""
import argparse
import collections
import csv

GROUP = {**{f"172.18.0.{n}": "A" for n in (101, 102, 103, 104)},
         **{f"172.18.0.{n}": "B" for n in (110, 111, 112, 113, 114)},
         **{f"172.18.0.{n}": "C" for n in (120, 121, 122, 123, 124)}}

IMAGES = {"A": "deliberately vulnerable",
          "B": "official, several years old",
          "C": "official, current"}

SCANNERS = [
    ("OpenVAS", ["processed/findings_openvas_a2.csv",
                 "processed/findings_openvas_b2.csv",
                 "processed/findings_openvas_c.csv"]),
    ("Nessus", ["processed/findings_nessus_a2.csv",
                "processed/findings_nessus_b2.csv",
                "processed/findings_nessus_c.csv"]),
    ("Qualys", ["processed/findings_qualys_corpus.csv"]),
]


def istrue(v):
    return str(v).strip().lower() in ("true", "1")


def load(files):
    rows = []
    for f in files:
        try:
            rows += list(csv.DictReader(open(f, encoding="utf-8")))
        except FileNotFoundError:
            pass
    return rows


def tally(rows):
    """Per group: findings (non-Log), KEV findings (non-Log, has_kev), and the host set."""
    find = collections.Counter()
    kev = collections.Counter()
    hosts = collections.defaultdict(set)
    for r in rows:
        g = GROUP.get(r["host"].strip())
        if not g:
            continue
        hosts[g].add(r["host"].strip())
        if r.get("threat") == "Log":
            continue
        find[g] += 1
        if istrue(r.get("has_kev")) or (r.get("kev_cves") or "").strip():
            kev[g] += 1
    return find, kev, hosts


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args()

    data = {name: tally(load(files)) for name, files in SCANNERS}
    hosts = {g: set() for g in "ABC"}
    for _name, (_f, _k, h) in data.items():
        for g in "ABC":
            hosts[g] |= h[g]

    lines = [
        "% generated by corpus_table.py from the current parsed findings; do not edit by hand",
        r"\begin{tabular}{llrrrrrr}",
        r"\toprule",
        r" & & & \multicolumn{3}{c}{Findings} & & \\",
        r"Group & Images & Hosts & OpenVAS & Nessus & Qualys & Per host & KEV \\",
        r"\midrule",
    ]
    tot = collections.Counter()
    for g in "ABC":
        nh = len(hosts[g])
        ov = data["OpenVAS"][0][g]
        ne = data["Nessus"][0][g]
        qu = data["Qualys"][0][g]
        kev = data["OpenVAS"][1][g] + data["Nessus"][1][g] + data["Qualys"][1][g]
        per = (ov + ne + qu) / nh
        bold = (lambda x: f"\\textbf{{{x}}}") if g == "C" else (lambda x: f"{x}")
        lines.append(
            f"{g} & {IMAGES[g]} & {nh} & {ov} & {ne} & {qu} & {per:.1f} & {bold(kev)} \\\\")
        tot["ov"] += ov; tot["ne"] += ne; tot["qu"] += qu; tot["kev"] += kev; tot["hosts"] += nh
    lines += [r"\bottomrule", r"\end{tabular}"]

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    # Totals the prose cites, printed so they are read off the same computation as the table.
    ab = {s: sum(data[s][0][g] for g in "AB") for s in ("OpenVAS", "Nessus", "Qualys")}
    print(f"wrote {args.out}")
    print(f"  full corpus, OpenVAS+Nessus : {tot['ov'] + tot['ne']}  "
          f"(+Qualys {tot['qu']} = {tot['ov'] + tot['ne'] + tot['qu']})")
    print(f"  two-scanner (A+B) OV+Ne     : {ab['OpenVAS'] + ab['Nessus']}  "
          f"(+Qualys {ab['Qualys']} = {ab['OpenVAS'] + ab['Nessus'] + ab['Qualys']})")
    print(f"  per group OV/Ne/Qu          : "
          + " | ".join(f"{g} {data['OpenVAS'][0][g]}/{data['Nessus'][0][g]}/{data['Qualys'][0][g]}"
                       for g in "ABC"))


if __name__ == "__main__":
    main()
